/**
 * Build-time ONLY: use QR Studio to validate invitation styles and emit the
 * small, limited set of supported drawing parameters for the React client.
 *
 * Intentionally no dynamic Studio imports in src/. The production app only
 * needs the Standard QR encoder (for per-room URLs) and compiled color values.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { generateQR } from './qr-studio/src/variants.js';
import { normalizeStyle, analyzeDesign } from './qr-studio/src/styles.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const designsPath = resolve(root, 'tools/qr-invitation-designs.json');
const outputPath = resolve(root, 'src/qr/presets.generated.js');
const testUrl = 'https://startup.example.org/join-game?code=ABC234';
const allowedPaints = new Set(['data', 'finder', 'finderCenter', 'background']);
const solidHex = /^#[0-9a-f]{6}$/i;
const fail = (id, reason) => { throw new Error(`Invitation preset '${id}': ${reason}`); };

function contrast(a, b) {
  const luminance = (hex) => {
    const s = hex.slice(1);
    const [r, g, blue] = [0, 2, 4].map((offset) => {
      const v = parseInt(s.slice(offset, offset + 2), 16) / 255;
      return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * blue;
  };
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}

function compileDesign(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) fail('?', 'expected an object');
  const { id, label, errorCorrection, style } = input;
  if (typeof id !== 'string' || !/^[a-z][a-z-]{1,30}$/.test(id)) fail(id, 'invalid ID');
  if (typeof label !== 'string' || !/^[\w -]{3,32}$/.test(label)) fail(id, 'invalid label');
  if (!['L', 'M', 'Q', 'H'].includes(errorCorrection)) fail(id, 'invalid error correction level');
  // Refuse to silently lose Studio capabilities that the tiny runtime cannot
  // reproduce; a designer must explicitly create a new runtime renderer first.
  const allowedStyleKeys = new Set(['size', 'quietZone', 'shape', 'moduleScale', 'paints']);
  for (const key of Object.keys(style ?? {})) {
    if (!allowedStyleKeys.has(key)) fail(id, `unsupported runtime style field '${key}'`);
  }
  for (const key of Object.keys(style?.paints ?? {})) {
    if (!allowedPaints.has(key)) fail(id, `unsupported paint '${key}'`);
  }
  const s = normalizeStyle(style);
  if (s.shape !== 'square' || s.moduleScale !== 1) fail(id, 'only full-sized square modules are supported');
  if (s.quietZone < 4) fail(id, 'standard QR codes need a quiet zone of at least 4 modules');
  if (s.size !== 384) fail(id, 'QR artwork size should be 384 for this interface');
  const paints = s.paints ?? {};
  const background = paints.background ?? s.background;
  const data = paints.data ?? s.foreground;
  const finder = paints.finder ?? data;
  const finderCenter = paints.finderCenter ?? finder;
  for (const [name, value] of Object.entries({ background, data, finder, finderCenter })) {
    if (typeof value !== 'string' || !solidHex.test(value)) fail(id, `${name} must be an opaque six-digit solid hex color`);
  }
  // A high contrast bar is intentional: these QR codes will be scanned from
  // displays, possibly at a distance, and sometimes inside a 3D animation.
  for (const [name, value] of Object.entries({ data, finder, finderCenter })) {
    if (contrast(value, background) < 7) fail(id, `${name} contrast is too low for a projected invitation`);
  }
  const qr = generateQR(testUrl, { kind: 'standard', errorCorrection });
  const errors = analyzeDesign(qr, s).filter((warning) => warning.severity === 'error');
  if (errors.length) fail(id, errors.map((warning) => warning.code).join(', '));
  return { id, label, errorCorrection, quietZone: s.quietZone, background, data, finder, finderCenter };
}

const designs = JSON.parse(await readFile(designsPath, 'utf8'));
if (!Array.isArray(designs) || !designs.length || designs.length > 8) throw new Error('Expected 1–8 invitation preset designs');
const compiled = designs.map(compileDesign);
if (new Set(compiled.map((style) => style.id)).size !== compiled.length) throw new Error('Duplicate invitation preset IDs');
if (!compiled.some((style) => style.id === 'scripture')) throw new Error("The 'scripture' default preset is required");

const output = `// GENERATED by tools/compile-qr-presets.mjs; edit tools/qr-invitation-designs.json instead.\n` +
  `// QR Studio validates source styles; only the scanner-safe values below ship.\n` +
  `export const INVITATION_QR_PRESETS = Object.freeze(${JSON.stringify(compiled, null, 2)}.map((preset) => Object.freeze(preset)));\n` +
  `export const DEFAULT_INVITATION_QR_PRESET = 'scripture';\n`;

if (process.argv.includes('--check')) {
  if (await readFile(outputPath, 'utf8').catch(() => '') !== output) {
    throw new Error('QR preset output is stale. Run npm run qr:presets.');
  }
  console.log('QR invitation presets are current.');
} else {
  await writeFile(outputPath, output);
  console.log(`Compiled ${compiled.length} QR invitation presets (QR Studio remains source-only).`);
}
